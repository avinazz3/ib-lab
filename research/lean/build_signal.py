"""Bundle the shared signal rules for a single-file QuantConnect project."""

import argparse
import ast
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MODULES = (
    "src/ib_lab/models.py",
    "src/ib_lab/historical.py",
    "src/ib_lab/screen.py",
)
LOCAL_FUNCTIONS = {
    "src/ib_lab/models.py": {"read_universe", "aware_timestamp"},
    "src/ib_lab/screen.py": {"screen"},
}


def bundle(*, execution: bool = False) -> str:
    parts = ["# Generated by research/lean/build_signal.py\nfrom __future__ import annotations\n"]
    execution_modules = ("src/ib_lab/entry.py", "research/lean/execution.py") if execution else ()
    for path in (*MODULES, *execution_modules, "research/lean/signal.py"):
        source = (ROOT / path).read_text()
        lines = source.splitlines(keepends=True)
        for node in ast.parse(source).body:
            internal_import = (
                isinstance(node, ast.ImportFrom)
                and node.module
                and (
                    node.module == "__future__"
                    or node.module.startswith("ib_lab.")
                    or node.module == "research.lean.execution"
                )
            )
            local_function = isinstance(node, ast.FunctionDef) and node.name in LOCAL_FUNCTIONS.get(
                path, ()
            )
            if internal_import or local_function:
                for i in range(node.lineno - 1, node.end_lineno):
                    lines[i] = ""
        parts.append(f"# {path}\n{''.join(lines).strip()}\n")
    config = json.loads((ROOT / "configs/breakout-review.json").read_text())
    parts.append(f"LeanSignalReplay.config = BreakoutConfig(**{config!r})\n")
    parts.append(f"LeanSignalReplay.simulate_entries = {execution!r}\n")
    return "\n".join(parts)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--execution", action="store_true", help="Enable the one-session entry pilot"
    )
    print(bundle(execution=parser.parse_args().execution), end="")
